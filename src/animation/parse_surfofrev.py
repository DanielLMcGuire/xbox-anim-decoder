results = []
for e in entries:
    inner = e[1:-1]
    depth = 0
    pts_end = None
    for i, ch in enumerate(inner):
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                pts_end = i
                break
    pts_block = inner[1:pts_end]
    rest = inner[pts_end+1:].lstrip(',')
    pts_vals = [float(x.strip().rstrip('f')) for x in pts_block.split(',') if x.strip() != '']
